#include<stdio.h>

int main()
{
    char ch = 'A';
    int i = 11;
    float no = 3.14f;
    double d = 9.8756234;

    printf("%c\n",ch);
    printf("%d\n",i);
    printf("%f\n",no);
    printf("%lf\n",d);

    return 0;
}

